#!/usr/bin/env python3
"""Convert CODOL-AssetExplorer's transpiled 1.1.1.13 zone loaders (C#) into the C++ include file used by codol_zone.

    python transpile_cs_loaders.py <GeneratedLoaders.cs> <loaders_1_1_1_13.inc>

Input : CODOL-AssetExplorer/src/Codol.FastFiles/Emulation/Generated/V1_1_1_13/GeneratedLoaders.cs
        ( itself generated by tools/ida/transpile_loaders.py from codoMP_client_shipRetail.exe 1.1.1.13 )
Output: the body of `struct Loaders` in codol_zone/src/zone_load.cpp. The translation is purely syntactic; the C#
        statements are kept one to one so the two files can be diffed line by line.
"""
import re
import sys


def convert(src: str) -> str:
    out = []
    lines = src.splitlines()
    i = 0
    in_class = False
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        i += 1
        if not in_class:
            if s.startswith('internal sealed partial class GeneratedLoaders'):
                in_class = True
                i += 1  # opening brace
            continue
        if s.startswith('internal static readonly (uint Address, byte[] Data)[] InitialGlobals'):
            # ( address, bytes ) pairs
            i += 1
            out.append('    static void write_initial_globals(VMem& m)')
            out.append('    {')
            while not lines[i].strip().startswith(']'):
                m = re.match(r'\((0x[0-9A-F]+)U, \[(.*)\]\),', lines[i].strip())
                if not m:
                    raise SystemExit('unexpected InitialGlobals entry: ' + lines[i])
                for n, b in enumerate(m.group(2).split(',')):
                    out.append('        m.WU8(%sU + %dU, static_cast<byte>(%s));' % (m.group(1), n, b.strip()))
                i += 1
            out.append('    }')
            i += 1
            continue
        if s == '}' and line.startswith('}'):
            break  # end of class
        if s.startswith('internal const int TranspiledFunctionCount'):
            out.append('    static constexpr int TranspiledFunctionCount = %s' % s.split('=')[1].strip())
            continue
        if s == 'try':
            continue
        if s == 'finally':
            # finally { M.StackLeave(N); }  ->  handled by the StackGuard emitted with StackEnter
            if lines[i].strip() != '{' or 'M.StackLeave(' not in lines[i + 1] or lines[i + 2].strip() != '}':
                raise SystemExit('unexpected finally block at line %d' % i)
            i += 3
            continue
        line = re.sub(r'^(\s*)internal ', r'\1', line)
        line = line.replace('unchecked(', '(')
        line = re.sub(r'\bRt\.(PreAdd|PostAdd)\(ref ', r'Rt::\1(', line)
        line = line.replace('Rt.Discard(', 'Rt::Discard(')
        line = re.sub(r'(0x[0-9A-Fa-f]+)UL\b', r'\1ULL', line)
        line = line.replace('return default;', 'return {};')
        m = re.match(r'^(\s*)uint _sp = M\.StackEnter\((0x[0-9A-F]+U)\);$', line)
        if m:
            out.append(line)
            out.append('%sStackGuard _sg{ M, %s };' % (m.group(1), m.group(2)))
            continue
        if re.search(r'\b(ref|default|checked|typeof|is|as|new|var|out)\b', re.sub(r'//.*', '', line)):
            raise SystemExit('unconverted C# construct at line %d: %s' % (i, line))
        out.append(line)
    return '\n'.join(out) + '\n'


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    with open(sys.argv[1], encoding='utf-8-sig') as f:
        src = f.read()
    body = convert(src)
    header = ('// GENERATED FILE - do not edit. Produced by codol_zone/tools/transpile_cs_loaders.py from\n'
              '// CODOL-AssetExplorer src/Codol.FastFiles/Emulation/Generated/V1_1_1_13/GeneratedLoaders.cs, which is the\n'
              '// machine translation ( tools/ida/transpile_loaders.py ) of the zone loaders of codoMP_client_shipRetail.exe,\n'
              '// Call of Duty Online 1.1.1.13. Function names are the addresses of the original functions.\n\n')
    with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
        f.write(header + body)


if __name__ == '__main__':
    main()
